import { CaptionSegment, WordTimestamp } from '../types';
import { formatTime } from './wavConverter';

/**
 * Format timestamp to SubRip (.srt) time string: 00:00:01,500
 */
function toSrtTime(seconds: number): string {
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);
  const millis = Math.floor((seconds % 1) * 1000);

  return `${hours.toString().padStart(2, '0')}:${minutes.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')},${millis.toString().padStart(3, '0')}`;
}

/**
 * Format timestamp to WebVTT (.vtt) time string: 00:00.500
 */
function toVttTime(seconds: number): string {
  const minutes = Math.floor(seconds / 60);
  const secs = Math.floor(seconds % 60);
  const millis = Math.floor((seconds % 1) * 1000);

  return `${minutes.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}.${millis.toString().padStart(3, '0')}`;
}

export function generateSrt(captions: CaptionSegment[]): string {
  return captions
    .map((c, index) => {
      const num = index + 1;
      const start = toSrtTime(c.start);
      const end = toSrtTime(c.end);
      return `${num}\n${start} --> ${end}\n${c.text.trim()}\n`;
    })
    .join('\n');
}

export function generateVtt(captions: CaptionSegment[]): string {
  const header = 'WEBVTT - Generated by Viral Voiceover Studio\n\n';
  const body = captions
    .map((c) => {
      const start = toVttTime(c.start);
      const end = toVttTime(c.end);
      return `${start} --> ${end}\n${c.text.trim()}\n`;
    })
    .join('\n');

  return header + body;
}

export function generateFormattedTranscript(captions: CaptionSegment[], allWords?: WordTimestamp[]): string {
  let output = `--- TRANSCRIPTION & TIMESTAMPS ---\n\n`;
  captions.forEach((c) => {
    output += `[${formatTime(c.start)} -> ${formatTime(c.end)}] ${c.text}\n`;
  });
  return output;
}

export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
